
const assert=require('assert');
const {load}=require('./sandbox');
const env=load({interactive:true}),t=env.api,s=t.state;
s.power=false;s.motors=[];s.relays=[];s.wires=[];
s.devices=[{id:1,type:'bulb',ratedPower:100,x:100,y:100}];t.renderAll();t.resetActionHistory();
function change(fn){t.beginActionHistory();fn();t.finishActionHistory();}
for(let n=101;n<=107;n++)change(()=>{s.devices[0].ratedPower=n;});
assert.strictEqual(t.actionCounts().undo,5);
for(let n=0;n<5;n++)assert.strictEqual(t.undoAction(),true);
assert.strictEqual(s.devices[0].ratedPower,102,'удерживаются только последние пять действий');
assert.strictEqual(t.undoAction(),false);
assert.strictEqual(t.actionCounts().redo,5);
for(let n=0;n<5;n++)assert.strictEqual(t.redoAction(),true);
assert.strictEqual(s.devices[0].ratedPower,107);
assert.strictEqual(t.redoAction(),false);
t.undoAction();change(()=>{s.devices[0].ratedPower=300;});
assert.strictEqual(t.actionCounts().redo,0,'новое действие очищает повтор');
t.resetActionHistory();
change(()=>{s.devices[0].x=400;});
const v=JSON.stringify(t.touchView());t.undoAction();
assert.strictEqual(s.devices[0].x,100);assert.strictEqual(JSON.stringify(t.touchView()),v);
t.redoAction();assert.strictEqual(s.devices[0].x,400);
change(()=>{s.wires.push({id:1,a:{devId:'IN',key:'L1'},b:{devId:1,key:'L'},color:'#8b5a2b',shape:'smooth',pts:[],sectionMm2:2.5});});
t.undoAction();assert.strictEqual(s.wires.length,0);
t.redoAction();assert.strictEqual(s.wires.length,1);
change(()=>{s.devices=[];s.wires=[];});
t.undoAction();assert.strictEqual(s.devices.length,1);assert.strictEqual(s.wires.length,1,'связанные провода восстанавливаются вместе с объектом');
t.redoAction();assert.strictEqual(s.devices.length,0);
s.devices=[{id:4,type:'meter',x:100,y:100,energyKwh:1}];t.renderAll();t.resetActionHistory();
change(()=>{s.devices[0].x=250;});
s.devices[0].energyKwh=2.5;t.undoAction();
assert.strictEqual(s.devices[0].x,100);assert.strictEqual(s.devices[0].energyKwh,2.5,'показания счётчика не откатываются');
t.redoAction();assert.strictEqual(s.devices[0].energyKwh,2.5);
const snapshot=t.schemeSnapshot('test');t.applyPreset(snapshot);
assert.strictEqual(t.actionCounts().undo,0,'открытие схемы сбрасывает историю');
assert.strictEqual(t.actionCounts().redo,0);
console.log('История: пять отмен и повторов, новая ветка, характеристики, провода, удаление, масштаб и показания — проверки пройдены.');

