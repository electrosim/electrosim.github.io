/* Пересоздать растровые миниатюры после изменения рисунков: node tools/build-tray-previews.js */
const fs=require('node:fs/promises'),path=require('node:path'),http=require('node:http');
const {createHash}=require('node:crypto'),{load}=require('./sandbox');
const root=path.resolve(__dirname,'..'),output=path.join(root,'assets','tray-previews');
function hash(text){return createHash('sha256').update(text).digest('hex');}
function playwright(){
  try{return require('playwright');}catch(error){
    return require(path.join(require('node:os').homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
  }
}
async function main(){
  const {api:t}=load(),entries=[];
  function add(type,special){
    const size=t.trayPreviewGeometry(type,special),svg=t.trayPreviewSvg(type,special),key=t.trayRasterKey(type,special);
    entries.push({key,svg,width:type==='comb'?64:74*size.w/size.h});
  }
  for(const type of Object.keys(t.STOCK))if(type!=='comb')add(type,null);
  for(const poles of [1,2,3])for(let count=1;count<=Math.floor(t.SLOTS/poles);count++){
    Object.assign(t.combTraySettings,{combPoles:poles,combCount:count});add('comb',null);
  }
  for(const special of ['conduit','clamp','motor','dcmotor','pushbutton','multimeter'])add(null,special);
  t.state.special.inbox=true;add(null,'panel');
  for(const voltage of [220,380]){
    t.state.panels[0].inletVoltage=voltage;
    Object.assign(t.state.specialProps.inbox,{ratedVoltage:voltage,frequency:50});
    add(null,'inbox');t.state.special.inbox=false;add(null,'panel');
  }
  let active;
  const server=http.createServer(async(req,res)=>{
    try{
      if(req.url==='/__preview__'){
        res.setHeader('Content-Type','text/html; charset=utf-8');
        res.end('<!doctype html><meta charset="utf-8"><style>html,body{margin:0;background:transparent;font:14px "Segoe UI",Roboto,Arial,sans-serif}#preview{width:'+active.width+'px;height:74px}#preview>svg{display:block;width:100%;height:100%}</style><div id="preview">'+active.svg+'</div>');
        return;
      }
      const file=path.resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));
      if(!file.startsWith(root+path.sep))throw new Error('outside root');
      res.setHeader('Content-Type',path.extname(file)==='.png'?'image/png':'application/octet-stream');
      res.end(await fs.readFile(file));
    }catch(error){res.statusCode=404;res.end();}
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const url='http://127.0.0.1:'+server.address().port;
  let browser;
  try{
    const pw=playwright(),edge=path.join(process.env['ProgramFiles(x86)']||'C:/Program Files (x86)','Microsoft/Edge/Application/msedge.exe');
    const edgeExists=await fs.access(edge).then(()=>true,()=>false);
    browser=await pw.chromium.launch({headless:true,...(edgeExists?{executablePath:edge}:{})});
    const context=await browser.newContext({viewport:{width:400,height:90},deviceScaleFactor:3});
    const page=await context.newPage(),catalog={};
    await fs.mkdir(output,{recursive:true});
    for(const entry of entries){
      active=entry;
      await page.goto(url+'/__preview__');
      await page.evaluate(async()=>{
        await document.fonts.ready;
        await Promise.all(Array.from(document.querySelectorAll('svg image')).map(async el=>{
          const img=new Image();img.src=el.getAttribute('href');await img.decode();
        }));
      });
      const sourceHash=hash(entry.svg),filename=entry.key.replace(/[^a-z0-9_-]/gi,'-')+'-'+hash('raster-v1\n'+entry.svg).slice(0,12)+'.png';
      await page.locator('#preview').screenshot({path:path.join(output,filename),omitBackground:true});
      catalog[entry.key]={src:'assets/tray-previews/'+filename,sourceHash};
    }
    await fs.writeFile(path.join(output,'catalog.js'),'/* Generated by tools/build-tray-previews.js. */\nglobalThis.ELECTROSIM_TRAY_PREVIEWS='+JSON.stringify(catalog,null,2)+';\n');
    console.log('Готовые миниатюры: '+entries.length+' PNG, масштаб 3×.');
  }finally{
    if(browser)await browser.close();
    await new Promise(resolve=>server.close(resolve));
  }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
