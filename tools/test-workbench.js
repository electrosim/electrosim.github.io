/* Пустой учебный стенд: окружение сохраняется, гофра не заменяет электрические провода. */
const assert=require('assert'),fs=require('fs'),path=require('path'),{load}=require('./sandbox');
const e=load({interactive:true}),t=e.api,s=t.state,base=t.schemeSnapshot('Обычный щит');
assert(s.workbench,'исходная сцена содержит верстак');
assert.equal(s.motors.length,2,'исходная сцена содержит АД и ДПТ');
assert(s.motors.find(m=>m.kind==='dc').x<s.motors.find(m=>m.kind==='ac').x,'ДПТ слева, АД справа');
assert.equal(s.devices.length,0);assert.equal(s.wires.length,0);
assert.equal(s.special.multimeter,false);
assert.equal(t.touchView().w,2800,'верстак с обоими двигателями целиком виден при запуске');
assert.equal(t.touchView().h,2500,'высота и размер объектов сохранены');
t.markSchemeClean();t.newWorkspaceScheme();
assert(s.workbench);assert.equal(s.motors.length,2,'новая схема тоже создаёт оба стенда');
assert.equal(t.touchView().w,2800);
const preset=JSON.parse(fs.readFileSync(path.join(__dirname,'../presets/Стенд двигателя — пустой.ad-scheme.json'),'utf8')).preset;
assert(t.folderPresets().some(p=>p.name===preset.name),'стенд автоматически появился в каталоге');
assert(t.applyPreset(preset));
assert.equal(s.devices.length,0);assert.equal(s.relays.length,0);assert.equal(s.wires.length,0);
assert.equal(s.motors.length,2);assert.equal(s.panels.length,1);
assert.equal(s.panels[0].railCount,2);assert.equal(s.special.multimeter,false);
assert.equal(t.motorPhaseDirection(s.motors[0]),0,'гофра не подаёт напряжение на двигатель');
assert(e.els.workbenchLayer.innerHTML.includes('class="workbench"'));
assert(e.els.conduitLayer.innerHTML.includes('class="motor-conduit"'));
assert.equal((e.els.workbenchLayer.innerHTML.match(/class="motor-mounting-plate"/g)||[]).length,2);
assert.equal((e.els.conduitLayer.innerHTML.match(/class="motor-instrument-conduit"/g)||[]).length,2);
assert.equal(t.mountingRails().length,2,'пустой щит допускает монтаж на две рейки');
const saved=t.schemeSnapshot('Работа студента');
assert.deepEqual(saved.state.workbench,preset.state.workbench);
const restored=load();assert(restored.api.applyPreset(saved));
assert.deepEqual(restored.api.state.workbench,saved.state.workbench);
assert(restored.els.workbenchLayer.innerHTML.includes('motor-mounting-plate'));
const matrix={a:1,b:0,c:0,d:1,e:0,f:0,inverse(){return this;}};
e.els.world.getScreenCTM=()=>matrix;e.els.scene.getScreenCTM=()=>matrix;
const body=e.makeEl('g');body.classList.add('motor-draggable');body.dataset.dev='M1';body.parentNode=e.els.motorLayer;
const before=e.els.conduitLayer.innerHTML,x=s.motors[0].x;
e.pointer(body,'pointerdown',{pointerType:'mouse',clientX:1400,clientY:1050});
e.pointer(e.window.document,'pointermove',{pointerType:'mouse',clientX:1460,clientY:1050});
e.pointer(e.window.document,'pointerup',{pointerType:'mouse',clientX:1460,clientY:1050});
assert.equal(s.motors[0].x,x+60);assert.notEqual(e.els.conduitLayer.innerHTML,before,'гофра следует за двигателем');
const moved=e.els.conduitLayer.innerHTML;s.panels[0].x+=30;t.renderAll();
assert.notEqual(e.els.conduitLayer.innerHTML,moved,'гофра следует за щитом');
t.resetActionHistory();t.beginActionHistory();s.motors=[];t.renderAll();t.finishActionHistory();
assert.equal(e.els.conduitLayer.innerHTML,'','после удаления двигателя гофра исчезает');
assert(!e.els.workbenchLayer.innerHTML.includes('motor-mounting-plate'));
assert(t.undoAction());assert(e.els.conduitLayer.innerHTML.includes('motor-conduit'));
assert(t.redoAction());assert.equal(e.els.conduitLayer.innerHTML,'');
delete base.state.workbench;assert(t.applyPreset(base));
assert.equal(s.workbench,null);assert.equal(e.els.workbenchLayer.innerHTML,'');assert.equal(e.els.conduitLayer.innerHTML,'');
const legacy=JSON.parse(JSON.stringify(preset));
legacy.state.motors=legacy.state.motors.filter(m=>m.kind==='ac');
legacy.state.motors[0].x=1250;legacy.state.panels[0].x=160;
legacy.state.workbench={x:60,y:1350,width:1900,height:520,panelId:'PN1',motorId:'M1'};
delete legacy.view;assert(t.applyPreset(legacy));
assert.equal(s.motors.length,1,'старое сохранение не получает лишний двигатель');
assert.equal(t.touchView().w,2000,'у старого стенда сохраняется прежний масштаб');
console.log('Пустой стенд: каталог, сохранение, отсутствие схемы, перенос и история — проверки пройдены.');
