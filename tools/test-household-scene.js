function checkInlet(api){
  const map=api.potentialMap(),phase=map.pot['IN/L1'],neutral=map.pot['IN/N'],earth=map.pot['IN/PE'];
  assert(phase&&neutral&&earth,'ввод содержит фазу, нейтраль и PE');
  assert.equal(map.conflict,false);
  assert(Math.abs(Math.hypot(phase.r-neutral.r,phase.i-neutral.i)-220)<1e-6,'на вводе L–N есть 220 В');
  assert(Math.abs(Math.hypot(phase.r-earth.r,phase.i-earth.i)-220)<1e-6,'на вводе L–PE есть 220 В');
  assert.equal(phase.frequencyHz,50);
}
