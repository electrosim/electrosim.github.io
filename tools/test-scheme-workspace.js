/* Файлы схем, отмена замены и восстановление без браузера. */
const assert=require('assert');
const {load}=require('./sandbox');
const env=load({interactive:true}),t=env.api,s=t.state;
let downloaded=null;
env.window.Blob=function(parts){downloaded=JSON.parse(parts.join(''));};
env.window.FileReader=function(){this.readAsText=file=>{this.result=file.text;this.onload();};};
assert(!t.schemeHasChanges(),'начальная схема не должна считаться изменённой');
s.panels[0].railCount=3;
assert(t.schemeHasChanges(),'изменение количества реек не обнаружено');
env.els.presetName.value='Моя квартира';
assert(t.saveCurrentSchemeFile());
assert.strictEqual(downloaded.format,'ad-trainer-scheme');
assert.strictEqual(downloaded.preset.name,'Моя квартира');
assert.strictEqual(downloaded.preset.state.panels[0].railCount,3);
assert(!t.schemeHasChanges(),'после сохранения работа должна быть чистой');
assert(env.store[t.SCHEME_DRAFT_KEY],'нет автосохранения');
const source=downloaded.preset;
s.panels[0].railCount=4;
t.openSchemeFile({text:JSON.stringify(downloaded)});
assert.strictEqual(s.panels[0].railCount,4,'работа заменена до подтверждения');
assert(env.els.schemeReplaceModal.classList.contains('open'));
t.closeSchemeReplace();
assert.strictEqual(s.panels[0].railCount,4,'отмена не сохранила текущую работу');
t.openWorkspaceScheme(source);t.finishSchemeReplace(false);
assert.strictEqual(s.panels[0].railCount,3,'схема не открылась после подтверждения');
s.panels[0].railCount=5;
t.newWorkspaceScheme();t.finishSchemeReplace(true);
assert.strictEqual(downloaded.preset.state.panels[0].railCount,5,'сохранена не текущая работа');
assert.strictEqual(s.panels[0].railCount,2,'новая схема не содержит исходный щит');
assert.strictEqual(s.wires.length,0);
const before=t.schemeSnapshot('Новая');
t.openSchemeFile({text:'не json'});
assert.deepStrictEqual(t.schemeSnapshot('Новая').state,before.state,'ошибочный файл изменил сцену');
t.openSchemeFile({text:JSON.stringify({format:'ad-trainer-schemes',presets:[source,source]})});
assert(env.els.presetList.innerHTML.includes('Из открытого файла'),'нет выбора для файла из нескольких схем');
assert.strictEqual(s.panels[0].railCount,2,'пакет схем открыл первую без выбора');
s.panels[0].railCount=4;t.saveSchemeDraft();
const draft=env.store[t.SCHEME_DRAFT_KEY];
t.markSchemeClean();t.newWorkspaceScheme();
env.store[t.SCHEME_DRAFT_KEY]=draft;t.initSchemeWorkspace();
assert(!env.els.schemeRecovery.hidden,'нет предложения восстановить работу');
t.restoreWorkspaceScheme();
assert.strictEqual(s.panels[0].railCount,4,'автосохранение не восстановлено');
assert(t.schemeHasChanges(),'восстановленная несохранённая работа ошибочно считается сохранённой');
const a=t.schemeSnapshot('Сравнение'),b=JSON.parse(JSON.stringify(a));
b.view.x+=100;b.journal.items=[];
assert.strictEqual(t.schemeSignature(a),t.schemeSignature(b),'масштаб или журнал требуют сохранения схемы');
console.log('Файлы, подтверждение замены и восстановление: все проверки пройдены');
